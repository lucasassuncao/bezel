// halves is the cell for a top and a bottom pixel, lit or not.
var halves = [2][2]string{{" ", "▄"}, {"▀", "█"}}

// Big draws s in capitals, in a block font three rows tall and three columns
// a letter: a countdown or a score read from across the room. What the font
// lacks is blank, and every row is as wide, so effects work on it.
func Big(s string) string {
	var rows [3]strings.Builder
	for i, r := range []rune(s) {
		glyph, ok := font[unicode.ToUpper(r)]
		if !ok {
			glyph = font[' ']
		}
		for row := range rows {
			if i > 0 {
				rows[row].WriteByte(' ')
			}
			for x := range 3 {
				top := glyph[row*2][x] == '#'
				bottom := row*2+1 < 5 && glyph[row*2+1][x] == '#'
				rows[row].WriteString(halves[b2i(top)][b2i(bottom)])
			}
		}
	}
	return rows[0].String() + "\n" + rows[1].String() + "\n" + rows[2].String()
}

func b2i(b bool) int {
	if b {
		return 1
	}
	return 0
}
